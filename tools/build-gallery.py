#!/usr/bin/env python3
"""Scan img/gallery/ and write gallery-manifest.js.

A static page can't read a directory, so the gallery list is generated here and
committed alongside the photos. Re-run this any time photos are added or removed:

    python3 tools/build-gallery.py

Captions come from the filename: "wadi-disah-morning.jpg" -> "Wadi Disah Morning".
Rename files to caption them, or edit the `alt` values in the generated file by
hand — but a re-run will overwrite hand edits, so prefer renaming.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GALLERY = ROOT / "img" / "gallery"
MANIFEST = ROOT / "gallery-manifest.js"
EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif"}


def natural_key(path: Path):
    """Sort so photo-2 lands before photo-10."""
    return [int(p) if p.isdigit() else p.lower() for p in re.split(r"(\d+)", path.name)]


def caption(path: Path) -> str:
    words = re.sub(r"[-_]+", " ", path.stem).strip()
    words = re.sub(r"\s+", " ", words)
    return words[:1].upper() + words[1:] if words else path.name


def main() -> int:
    if not GALLERY.is_dir():
        print(f"No such directory: {GALLERY}", file=sys.stderr)
        return 1

    photos = sorted(
        (p for p in GALLERY.iterdir() if p.suffix.lower() in EXTENSIONS and not p.name.startswith(".")),
        key=natural_key,
    )

    entries = [{"src": f"img/gallery/{p.name}", "alt": caption(p)} for p in photos]

    body = json.dumps(entries, indent=2, ensure_ascii=False)
    MANIFEST.write_text(
        "// Generated by tools/build-gallery.py — do not edit by hand.\n"
        "// Re-run `python3 tools/build-gallery.py` after adding or removing photos.\n"
        f"window.GALLERY = {body};\n",
        encoding="utf-8",
    )

    print(f"Wrote {MANIFEST.relative_to(ROOT)} — {len(entries)} photo(s).")
    if not entries:
        print(f"  (nothing in {GALLERY.relative_to(ROOT)}/ yet)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
